@pytest.fixture(scope='module')
def sealed(tmp_path_factory):
    folder=tmp_path_factory.mktemp('mode-journal');patch=pytest.MonkeyPatch()
    patch.setattr(action_worker_lock,'ROOT',folder/'locks')
    try:
        runtime,_,_,_,_=source(folder,patch)
        capture=folder/'capture';result=stage(runtime,sha256(runtime/'result.json'),capture)
        yield capture,result['receipt_sha256']
    finally:patch.undo()


def advance(folder,receipt,n=1):
    return journal.advance(folder,receipt['checkpoint'],receipt['sha256'],maximum_samples=n)


def test_interruption_retains_only_completed_frames_and_matches_direct_full_query(tmp_path,monkeypatch,sealed):
    capture,pin=sealed;observed=load(capture,pin)
    expected,arrays=evaluate(observed.scene,read(observed.meta['policy_path']),sha256(observed.meta['contacts_path']),
        actor_vertices=observed.actor_vertices,object_poses=observed.object_poses)
    folder=tmp_path/'journal';initial=journal.prepare(capture,pin,folder)
    assert initial['completed_samples']==0 and not initial['sampled_conditions_pass']
    with pytest.raises(ValueError,match='Full original'):
        journal.finalize(folder,initial['checkpoint'],initial['sha256'],tmp_path/'too-early')
    first=advance(folder,initial);saved=(folder/first['checkpoint']).read_bytes()
    real=journal.evaluate;calls=[]
    def interrupted(*args,**kwargs):
        calls.extend(kwargs['sample_indices'])
        if kwargs['sample_indices']==[2]:raise RuntimeError('Interrupted before complete frame')
        return real(*args,**kwargs)
    monkeypatch.setattr(journal,'evaluate',interrupted)
    with pytest.raises(RuntimeError,match='Interrupted'):advance(folder,first,2)
    assert calls==[1,2] and (folder/first['checkpoint']).read_bytes()==saved
    progress=read(folder/'progress.json');assert progress['completed_samples']==2
    assert not progress['sampled_conditions_pass']
    calls=[]
    def tracked(*args,**kwargs):calls.extend(kwargs['sample_indices']);return real(*args,**kwargs)
    monkeypatch.setattr(journal,'evaluate',tracked)
    done=advance(folder,progress,4096)
    assert calls==list(range(2,len(expected['times_s']))) and done['population_complete']
    assert not done['sampled_conditions_pass']
    checked=journal.verify(folder,done['checkpoint'],done['sha256'])
    assert checked['population_complete'] and not checked['sampled_conditions_pass']
    result=journal.finalize(folder,done['checkpoint'],done['sha256'],tmp_path/'final')
    assert read(tmp_path/'final/geometry.json')==expected
    with np.load(tmp_path/'final/observations.npz',allow_pickle=False) as actual:
        assert set(actual.files)==set(arrays)
        for key,value in arrays.items():
            assert actual[key].dtype==value.dtype and actual[key].shape==value.shape and actual[key].tobytes()==value.tobytes()
    assert verify_archive(tmp_path/'final/observations.npz')['all_values_exact']
    assert result['sampled_conditions_pass']==expected['sampled_conditions_pass']
    assert result['source_scene_conditions_pass'] is False
    assert result['surface_receipt_sha256']==pin and result['matches_export_configuration']
    assert result['selected_root_modes']=={'A':'extracted','B':'embedded'}
    assert all(result[k] is False for k in ('quality_approved','physics_verified','release_approved'))
    assert len(list((folder/'frames').glob('000002-*')))==2


@pytest.mark.parametrize('fault',['pin','request','method','frame','array','receipt','gap','false-approval'])
def test_changed_provenance_or_checkpoint_cannot_resume(tmp_path,sealed,fault):
    capture,pin=sealed;folder=tmp_path/'journal';receipt=advance(folder,journal.prepare(capture,pin,folder))
    checkpoint=read(folder/receipt['checkpoint']);directory=folder/checkpoint['frame']['directory']
    if fault=='pin':receipt['sha256']='0'*64
    if fault=='request':save(folder/'request.json',{**read(folder/'request.json'),'schema':'old-import-capture'})
    if fault=='method':(folder/'implementation/native_runtime_geometry_journal.py').write_bytes(b'changed')
    if fault=='frame':save(directory/'geometry.json',{})
    if fault=='array':(directory/'observations.npz').write_bytes(b'changed')
    if fault=='receipt':save(directory/'receipt.json',{})
    if fault in ('gap','false-approval'):
        if fault=='gap':checkpoint['next_sample']=2
        else:checkpoint['sampled_conditions_pass']=True
        save(folder/receipt['checkpoint'],checkpoint);receipt['sha256']=sha256(folder/receipt['checkpoint'])
    with pytest.raises(ValueError):advance(folder,receipt)


@pytest.mark.parametrize('count',[0,True,4097])
def test_unbounded_or_noninteger_batches_reject(tmp_path,count):
    with pytest.raises(ValueError,match='Bounded complete-frame'):
        journal.advance(tmp_path,'missing','0'*64,maximum_samples=count)


def test_wrong_external_surface_pin_cannot_create_journal(tmp_path,sealed):
    capture,_=sealed;folder=tmp_path/'journal'
    with pytest.raises(ValueError,match='Pinned surface receipt'):journal.prepare(capture,'0'*64,folder)
    assert not folder.exists()


def test_journal_cannot_write_inside_immutable_surface_capture(sealed):
    capture,pin=sealed;folder=capture/'forbidden-journal'
    with pytest.raises(ValueError,match='Fresh separate'):journal.prepare(capture,pin,folder)
    assert not folder.exists()


def test_changed_request_during_query_does_not_publish_checkpoint(tmp_path,monkeypatch,sealed):
    capture,pin=sealed;folder=tmp_path/'journal';initial=journal.prepare(capture,pin,folder)
    real=journal.evaluate
    def changed(*args,**kwargs):
        result=real(*args,**kwargs);request=read(folder/'request.json');request['times_s'].pop()
        save(folder/'request.json',request);return result
    monkeypatch.setattr(journal,'evaluate',changed)
    with pytest.raises(ValueError,match='request changed during frame'):advance(folder,initial)
    assert read(folder/'progress.json')==initial
